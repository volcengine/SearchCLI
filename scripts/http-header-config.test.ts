async function testManualConfigOnlyAffectsExpectedRequestPlane(): Promise<void> {
  const tempDir = await mkdtemp(path.join(os.tmpdir(), 'viking-http-header-'));
  try {
    const configPath = path.join(tempDir, '.viking', 'config.json');
    await mkdir(path.dirname(configPath), { recursive: true });
    await writeFile(
      configPath,
      JSON.stringify({
        host: 'search.example.com',
        'x-tt-backend': 'stable-backend'
      }),
      'utf8'
    );

    process.env.VIKING_CONFIG_PATH = configPath;

    const serviceConfig = resolveServiceConfig(baseServiceConfigInput());
    assert.equal(serviceConfig.xTtBackend, 'stable-backend');
    assert.equal(serviceConfig.dataPlaneHost, 'search.example.com');

    let openApiHeader: string | null = null;
    let openApiHostHeader: string | null = null;
    globalThis.fetch = async (_input: string | URL | Request, init?: RequestInit): Promise<Response> => {
      openApiHeader = readHeader(init?.headers, 'x-tt-backend');
      openApiHostHeader = readHeader(init?.headers, 'host');
      return new Response('{}', { status: 200, headers: { 'content-type': 'application/json' } });
    };

    await requestOpenApiJson(serviceConfig, 'POST', '/api/v1/ListDataset', { ProjectName: 'demo-project' });
    assert.equal(openApiHeader, 'stable-backend');
    assert.equal(openApiHostHeader, 'open.example.com');

    const runtimeConfig = resolveRuntimeConfig({
      ...baseRuntimeConfigInput(),
      applicationId: 'app-1',
      datasetId: 'dataset-1'
    });
    const runtimeHeaders = buildSignedRequestHeaders(
      runtimeConfig,
      'POST',
      new URL('https://data.example.com/api/v1/application/app-1/search'),
      '{}',
      { 'content-type': 'application/json' }
    );
    assert.equal(runtimeHeaders['x-tt-backend'], undefined);
    assert.equal(runtimeHeaders.host, 'search.example.com');
  } finally {
    globalThis.fetch = originalFetch;
    await rm(tempDir, { recursive: true, force: true });
  }
}

async function testApiKeyOnlyAuthUsesBearerHeaders(): Promise<void> {
  const tempDir = await mkdtemp(path.join(os.tmpdir(), 'viking-http-header-'));
  try {
    const configPath = path.join(tempDir, '.viking', 'config.json');
    await mkdir(path.dirname(configPath), { recursive: true });
    await writeFile(configPath, '{}', 'utf8');
    process.env.VIKING_CONFIG_PATH = configPath;
    process.env.VIKING_API_KEY = 'runtime-api-key';

    const serviceConfig = resolveServiceConfig({
      controlPlaneBaseUrl: 'https://open.example.com',
      dataPlaneBaseUrl: 'https://data.example.com',
      region: 'cn-beijing',
      projectName: 'demo-project',
      timeoutMs: 5000
    });
    assert.equal(serviceConfig.apiKey, 'runtime-api-key');
    assert.equal(serviceConfig.authSource, 'api-key');

    const explicitAkSkConfig = resolveServiceConfig({
      controlPlaneBaseUrl: 'https://open.example.com',
      dataPlaneBaseUrl: 'https://data.example.com',
      apiKey: 'runtime-api-key',
      accessKeyId: 'flag-ak',
      secretKey: 'flag-sk',
      region: 'cn-beijing',
      projectName: 'demo-project',
      timeoutMs: 5000
    });
    assert.equal(explicitAkSkConfig.apiKey, undefined);
    assert.equal(explicitAkSkConfig.authSource, 'flag');

    let authorizationHeader: string | null = null;
    let hostHeader: string | null = null;
    globalThis.fetch = async (_input: string | URL | Request, init?: RequestInit): Promise<Response> => {
      authorizationHeader = readHeader(init?.headers, 'authorization');
      hostHeader = readHeader(init?.headers, 'host');
      return new Response('{}', { status: 200, headers: { 'content-type': 'application/json' } });
    };

    await requestJson(serviceConfig, 'POST', '/api/v1/application/app-1/search', { query: { text: 'demo' } });
    assert.equal(authorizationHeader, 'Bearer runtime-api-key');
    assert.equal(hostHeader, null);
    await assert.rejects(
      requestOpenApiJson(serviceConfig, 'POST', '/api/v1/ListDataset', { ProjectName: 'demo-project' }),
      /control-plane/
    );

    const runtimeConfig = resolveRuntimeConfig({
      controlPlaneBaseUrl: 'https://open.example.com',
      dataPlaneBaseUrl: 'https://data.example.com',
      applicationId: 'app-1',
      datasetId: 'dataset-1',
      region: 'cn-beijing',
      timeoutMs: 5000,
      defaultPageSize: 10,
      outputDir: '.viking/reports'
    });
    const runtimeHeaders = buildSignedRequestHeaders(
      runtimeConfig,
      'POST',
      new URL('https://data.example.com/api/v1/application/app-1/search'),
      '{}',
      { 'content-type': 'application/json' }
    );
    assert.equal(runtimeHeaders.authorization, 'Bearer runtime-api-key');
    assert.equal(runtimeHeaders.host, undefined);
  } finally {
    globalThis.fetch = originalFetch;
    await rm(tempDir, { recursive: true, force: true });
  }
}

