async function testHiddenKeysStayOutOfCliDisplayAndAutoGeneratedConfig(): Promise<void> {
  const tempDir = await mkdtemp(path.join(os.tmpdir(), 'viking-http-header-'));
  try {
    const configPath = path.join(tempDir, '.viking', 'config.json');
    await mkdir(path.dirname(configPath), { recursive: true });
    process.env.VIKING_CONFIG_PATH = configPath;

    assert.equal(listCliConfigKeys().includes('host'), false);
    assert.equal(listCliConfigKeys().includes('x-tt-backend'), false);

    await saveCliConfig({
      activeProfile: 'default',
      profiles: {
        default: {
          baseUrl: 'https://data.example.com',
          controlPlaneBaseUrl: 'https://open.example.com',
          dataPlaneBaseUrl: 'https://data.example.com',
          region: 'cn-beijing',
          projectName: 'demo-project',
          timeoutMs: 5000
        }
      }
    });

    const autoGeneratedRaw = await readFile(configPath, 'utf8');
    assert.equal(autoGeneratedRaw.includes('"host"'), false);
    assert.equal(autoGeneratedRaw.includes('"x-tt-backend"'), false);

    await writeFile(
      configPath,
      JSON.stringify({
        host: 'search.example.com',
        'x-tt-backend': 'stable-backend',
        region: 'cn-beijing'
      }),
      'utf8'
    );

    const loaded = loadCliConfigSync(configPath);
    const visibleEntries = formatCliConfigEntries(loaded, false);
    assert.equal(visibleEntries.some(entry => entry.key === 'host'), false);
    assert.equal(visibleEntries.some(entry => entry.key === 'x-tt-backend'), false);
  } finally {
    await rm(tempDir, { recursive: true, force: true });
  }
}

