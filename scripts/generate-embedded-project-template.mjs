import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const templateRoot = path.join(root, 'templates', 'project-web');
const outputFile = path.join(root, 'src', 'project', 'embedded-project-template.ts');
const ignoredTemplateEntries = new Set([
  'node_modules',
  'dist',
  '.wrangler',
]);
const ignoredTemplatePaths = new Set([
  'apps/api/src/env.ts',
]);
const templateOutputPaths = new Map([
  ['apps/api/src/env.template.ts', 'apps/api/src/env.ts'],
]);

const files = await readDirectoryFiles(templateRoot, templateRoot);
const content = `// Copyright (c) 2026 ByteDance Ltd. and/or its affiliates
// SPDX-License-Identifier: Apache-2.0
// AUTO-GENERATED by scripts/generate-embedded-project-template.mjs. Do not edit manually.

export const PROJECT_WEB_TEMPLATE_VERSION = '1.0.0';

export const PROJECT_WEB_TEMPLATE_FILES: Record<string, string> = ${JSON.stringify(files, null, 2)};
`;

await writeFile(outputFile, content, 'utf8');
console.log(`Embedded project template written to ${outputFile}`);

async function readDirectoryFiles(baseDir, currentDir) {
  const entries = await readdir(currentDir, { withFileTypes: true });
  const sortedEntries = [...entries].sort((left, right) => left.name.localeCompare(right.name));
  const result = {};

  for (const entry of sortedEntries) {
    if (ignoredTemplateEntries.has(entry.name)) continue;
    const fullPath = path.join(currentDir, entry.name);
    if (entry.isDirectory()) {
      Object.assign(result, await readDirectoryFiles(baseDir, fullPath));
      continue;
    }
    if (!entry.isFile()) continue;
    const relativePath = path.relative(baseDir, fullPath).split(path.sep).join('/');
    if (ignoredTemplatePaths.has(relativePath)) continue;
    const outputPath = templateOutputPaths.get(relativePath) ?? relativePath;
    result[outputPath] = await readFile(fullPath, 'utf8');
  }

  return result;
}
